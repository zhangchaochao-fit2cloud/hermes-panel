    expect(proactive).toContain('icon="proactive"');
    expect(proactive).toContain('v-else-if="error"');
    expect(intent).toContain('FeatureTaskBridge');
    expect(intent).toContain('icon="intent"');
    expect(intent).toContain('retryLastError');

    expect(en).toContain('Use tools in Chat');
    expect(en).toContain('Use memory in Chat');
    expect(en).toContain('Plan with cost in Chat');
    expect(en).toContain('Plan goal in Chat');
    expect(en).toContain('Plan role room in Chat');
    expect(en).toContain('Plan diagnostics in Chat');
