    expect(cost).toContain('icon="cost"');
    expect(cost).toContain('ErrorBanner');
    expect(cost).toContain("command=\"hermes insights\"");
    expect(cost).toContain("secondary-to=\"/settings#providers\"");
    expect(cost).toContain('const error = ref<string | null>(null)');
    expect(cost).toContain('@retry="loadCostOverview"');
    expect(goals).toContain('FeatureTaskBridge');
    expect(goals).toContain('icon="goals"');
    expect(goals).toContain("secondary-to=\"/chat-room\"");
    expect(room).toContain('FeatureTaskBridge');
    expect(room).toContain('icon="chatRoom"');
    expect(room).toContain('room-task-bridge');
    expect(developer).toContain('FeatureTaskBridge');
    expect(developer).toContain('icon="developer"');
    expect(developer).toContain('command="hermes doctor"');
    expect(channels).toContain('FeatureTaskBridge');
    expect(channels).toContain('icon="channels"');
    expect(channels).toContain('command="hermes pairing list"');
    expect(channels).toContain('v-else-if="store.error"');
    expect(lessons).toContain('FeatureTaskBridge');
    expect(lessons).toContain('icon="lessons"');
    expect(lessons).toContain('v-else-if="error"');
    expect(sandbox).toContain('FeatureTaskBridge');
    expect(sandbox).toContain('icon="sandbox"');
    expect(sandbox).toContain('function checkSandboxAvailability');
    expect(audit).toContain('FeatureTaskBridge');
    expect(audit).toContain('icon="audit"');
    expect(audit).toContain('v-else-if="error"');
